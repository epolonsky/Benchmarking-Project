    my $result_ji;

    if($file_i ne $last_i && exists $lengths{$last_i}){ undef $lengths{$last_i}; }
    if($file_j ne $last_j && exists $lengths{$last_j}){ undef $lengths{$last_j}; }
    $last_i=$file_i; $last_j=$file_j;

    if ($file_i eq $file_j) {
      # Get lengths once is enough (selfblast)
      %lengths = %{&get_gene_lengths($file_i)};
    }
    else {
      %lengths = %{&get_gene_lengths($file_i,$file_j)};
    }
    my %seen;
    my %best;

    $result_ij = &blast($file_i,$file_j,$thread_id,\%lengths,\%seen,$cur_threads_per_process,$is_pipe_job);
    
    if($halfblast){

      # simply infer the evalue of the reciprocal hit directly instead of using blast
      # this is only an approximation !

      @{$result_ij} = map { my ($ga, $gb, $evalue_ab, $bitscore_ab) = split(" ",$_); 
                          $evalue_ab = sprintf("%.2e", ( $lengths{$file_j}{$ga} * 
                                            $lengths{$file_i}{"total"} ) / 
                                            (2**$bitscore_ab) );
                          my $evalue_ba = sprintf("%.2e", ( $lengths{$file_i}{$gb} * 
                                            $lengths{$file_j}{"total"} ) / 
                                            (2**$bitscore_ab) );
                          my $bitscore_ba=$bitscore_ab;
                          if($evalue_ba < $evalue){ 
                            if (!defined($best{$ga}) || $best{$ga} < $bitscore_ab) { $best{$ga} = $bitscore_ab; }
                            if (!defined($best{$gb}) || $best{$gb} < $bitscore_ba) { $best{$gb} = $bitscore_ba; }
                            ( "$ga $gb $evalue_ab $bitscore_ab $evalue_ba $bitscore_ba" )
                          }else{ if ($debug>1) {print STDERR "!$ga -> $gb not reciprocal\n";} () } }
                        @{$result_ij};
    }else{
      if ($file_i eq $file_j) {
        # One run is enough (selfblast)
        $result_ji = $result_ij;
      }else {
        $result_ji = &blast($file_j,$file_i,$thread_id,\%lengths,\%seen,$cur_threads_per_process,$is_pipe_job);
      }
    }

    # given two genes (and the source file name) the %seen contains index to the entry
    # with the lowest evalue (if any)
    # next to make the output reciprocal, edges are searched that exists in both directions

    if($interproscan){ # !! under development !!

      my %result_interpro = map { my ($a,$b,$d) = split(/\s+/); print STDERR "$a--$b=>$d\n"; "$a--$b" => $d } split "\n", `awk -f '$tmp_path/interproscan.awk' '$tmp_path$short_file_i.interproscan' '$tmp_path$short_file_j.interproscan' '$tmp_path$short_file_j.interproscan'`;

      @{$result_ij} = map {
        my @arr=split(/\s+/);
        #my ($query_id,$subject_id,$local_identity,$alignment_length,$mismatches,$openings,$query_start,$query_end,$subject_start,$subject_end,$local_evalue,$local_bitscore) = split(/\s+/);
