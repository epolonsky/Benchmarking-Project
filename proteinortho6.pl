        join "\t",@arr;
      } @{$result_ij};
    }

    if ($file_i eq $file_j && !$selfblast) {&Error("Selfblast is disabled but I want to check $file_i vs $file_j");}

    if(!$halfblast){
      @{$result_ij} = map { my ($ga, $gb, $evalue_ab, $bitscore_ab) = split(" ",$_); 
                            if(exists $seen{"$file_j $ga $gb"} && exists $seen{"$file_i $gb $ga"}){ 
                              my ($remote_ga, $remote_gb, $evalue_ba, $bitscore_ba) = split(" ",$result_ji->[$seen{"$file_i $gb $ga"}]); 
                              if (!defined($best{$ga}) || $best{$ga} < $bitscore_ab) { $best{$ga} = $bitscore_ab; }
                              if (!defined($best{$gb}) || $best{$gb} < $bitscore_ba) { $best{$gb} = $bitscore_ba; }
                              ( "$_ $evalue_ba $bitscore_ba" )
                            }else{ if ($debug>1) {print STDERR "!$ga -> $gb not reciprocal\n";} () } }
                          @{$result_ij};
    }
    # now the result_ij is reciprocal 
    # and the %best contains the best bitvalues for any gene
    # Remove worse entries based on the adaptive threshold (-sim)
    # sim=1 <=> reciprocal best match, sim=0.95 => top 5% below the the top hit
    @{$result_ij} = grep {
      my ($ga,$gb,$evalue_ab,$bitscore_ab,$evalue_ba,$bitscore_ba) = split(" ",$_);
      if ($debug>1 && !($best{$ga}*$sim <= $bitscore_ab && $best{$gb}*$sim <= $bitscore_ba)) {print STDERR "!$ga -> $gb not among the $sim top adaptive best hits\n";}
      $best{$ga}*$sim <= $bitscore_ab && $best{$gb}*$sim <= $bitscore_ba
    } @{$result_ij};

    if ($synteny) {
      my $synteny_temp_file = "${tmp_path}synteny-$project-$run_id-${thread_id}_${short_file_i}_vs_$short_file_j";
      $synteny_temp_file=~s/^\.\///;

      # Clean up, just to be safe
      if(!$keep){
        unlink("$synteny_temp_file.input");
        unlink("$synteny_temp_file.log");
        unlink("$synteny_temp_file.matching");    
      }

      my ($ordered_matches, $track_pointer, $close_copies_pointer) = &synteny_matches($result_ij,$file_i,$file_j);
      open(PREGRAPH,">$synteny_temp_file.input") || &Error("Could not open temp file '$synteny_temp_file.input': $!");
      print PREGRAPH $ordered_matches;
      close(PREGRAPH);
      my $ffadj_param = "-a $alpha";
      if ($duplication) { $ffadj_param .= " -R $duplication -M $cs";}
      my $cmd = "$po_path/proteinortho_ffadj_mcs.py $ffadj_param '$synteny_temp_file.input'; mv '$synteny_temp_file.input.matching' '$synteny_temp_file.matching'";
      if ($debug) {print STDERR "$cmd\n";}
      my $synt_stats = qx($cmd);
      $synt_stats=~s/[\r\n]+$//;
      $synt_stats =~ s/#.+\n//;

      # Reverse mapping of full gene ids, two seperate maps in case of overlapps in short ids
      my %full_id_map_i;
      my %full_id_map_j;
      foreach (@{$result_ij}) {
        my ($a,$b,$evalue_ab,$bitscore_ab,$evalue_ba,$bitscore_ba) = split(" ",$_);
        #my ($a, $b) = split(/\s/,$_);
        my $aa = &convertUniprotAndNCBI($a);
        my $bb = &convertUniprotAndNCBI($b);
        if ($aa ne $a) {
          if ($debug) {print STDERR "j_map: $aa -> $a\n";}
          $full_id_map_j{$aa} = $a;}
        if ($bb ne $b) {
          if ($debug) {print STDERR "i_map: $bb -> $b\n";}
          $full_id_map_i{$bb} = $b;}
      }

      # Reverse mapping of gene position to short id
      my %track = %{$track_pointer};
      my %close = %{$close_copies_pointer};
      # Generate hash for synteny hits
      my %synteny;

      unless (-s "$synteny_temp_file.matching") {
        print STDERR "\n$RED [Error] Failed to run $po_path/proteinortho_ffadj_mcs.py for\n$file_i vs $file_j\nMoving source to $synteny_temp_file.err for debugging\nI will continue, but results may be incomplete.$NC \n\n";
        system("mv $synteny_temp_file.input $synteny_temp_file.err");
        next;
      }

      my $OSYNGRAPH_CLEAN;
      if($keep){ open($OSYNGRAPH_CLEAN,">$synteny_temp_file.matching.clean") || &Error("Could not open temp file $synteny_temp_file.matching.clean: $!'");}

      open(OSYNGRAPH,"<$synteny_temp_file.matching") || &Error("Could not open temp file $synteny_temp_file.matching: $!'");
      while(<OSYNGRAPH>) {
        $_=~s/[\r\n]+$//;
        my ($chr_i, $i, $chr_j, $j, $direction, $score) = split(/\s+/,$_,6);


        if($i eq "TELOMERE_END" || $i eq "TELOMERE_START" || $j eq "TELOMERE_END" || $j eq "TELOMERE_START"){next}

        if (!defined($score) || $i =~ /[^0-9]/ || $i == 0 || length($i) > 10) {next;}

        
        unless (defined($track{$file_i.$i})) { print STDERR "Could not find i: $file_i.$i\n";  next; }
        unless (defined($track{$file_j.$j})) { print STDERR "Could not find j: $file_j.$j\n";  next; }


        # Remap to full ID
        my $a = $track{$file_i.$i};
        my $b = $track{$file_j.$j};

        if (defined($full_id_map_i{$a})) {$a = $full_id_map_i{$a};}
        if (defined($full_id_map_j{$b})) {$b = $full_id_map_j{$b};}

        if($keep){
          print $OSYNGRAPH_CLEAN "$chr_i\t$a\t$chr_j\t$b\t$direction\t$score\n";
        }

        # Store
        $synteny{"$b $a"} = "$direction\t$score";


        # Close copies
        if ($neighbourjoin && defined($close{$i})) {
          my @partners = split(',',$close{$i});
          foreach (@partners) {
            my $c = $track{$file_i.$_};
            if (defined($full_id_map_i{$c})) {$c = $full_id_map_i{$c};}
            # Store
            $synteny{"$b $c"} = "$direction\t$score";
            if ($debug) {print STDERR "Storing addional proximity edge $a & $b -> $c\n";}
          }
        }
      }
      close(OSYNGRAPH);
      if($keep){close($OSYNGRAPH_CLEAN)}
      if(!$keep){
        unlink("$synteny_temp_file.input");
        unlink("$synteny_temp_file.log");
        unlink("$synteny_temp_file.matching");
      }
      {
        lock($syn_lock);

        my @arr0; #evalue ab
        my @arr1; #biscore ab
        my @arr2; #evalue ba
        my @arr3; #bitscore ba
        foreach (@{$result_ij}) {
          my ($a,$b,$evalue_ab,$bitscore_ab,$evalue_ba,$bitscore_ba) = split(" ",$_);
          push(@arr0,$evalue_ab);
          push(@arr1,$bitscore_ab);
          push(@arr2,$evalue_ba);
          push(@arr3,$bitscore_ba);
        }

        open(SYN,">>$syngraph") || &Error("Could not open file '$syngraph': $!");
        print SYN "# $short_file_j\t$short_file_i\n";
        print SYN "# ".median(@arr0)."\t".median(@arr1)."\t".median(@arr2)."\t".median(@arr3)."\n";
        print SYN "# Scores: $synt_stats\n";
        foreach (@{$result_ij}) {
          my ($a,$b,$evalue_ab,$bitscore_ab,$evalue_ba,$bitscore_ba) = split(" ",$_);
          if (!defined($synteny{"$a $b"})) {if ($debug) {print STDERR "FAIL: $_\n";} next;}    # Not reported by gene-order algo
          my $line = "$_ ".$synteny{"$a $b"};
          $line =~ s/ /\t/g;
          print SYN "$line\n";
        }
        close(SYN);
      }

    }

    {
      lock($graph_lock);

      my @arr0; #evalue ab
      my @arr1; #biscore ab
      my @arr2; #evalue ba
      my @arr3; #bitscore ba
      foreach (@{$result_ij}) {
        my ($ga,$gb,$evalue_ab,$bitscore_ab,$evalue_ba,$bitscore_ba) = split(" ",$_);
        push(@arr0,$evalue_ab);
        push(@arr1,$bitscore_ab);
        push(@arr2,$evalue_ba);
        push(@arr3,$bitscore_ba);
      }

      my $simgraph_temp_file = "${tmp_path}simgraph-$project-$run_id-${thread_id}";

      open(my $GRAPH,">>$simgraph_temp_file") || &Error("Could not open file '$simgraph_temp_file': $!");
      print $GRAPH "# $short_file_j\t$short_file_i\n# ".median(@arr0)."\t".median(@arr1)."\t".median(@arr2)."\t".median(@arr3)."\n";
      foreach (@{$result_ij}) {
        my $line = $_;
        $line =~ s/ /\t/g;
        print $GRAPH "$line\n";
      }
      close($GRAPH);
    }
    # Count
    {
      lock($jobs_done);
      $jobs_done++;
    }
    &print_blast_stats(); # Needs jobs_done to be free
  }
}

sub sum {
  my $ret = 0;
  foreach (@_){
    $ret += $_;
  }
  return $ret;
}
sub median {
  sum( ( sort { $a <=> $b } @_ )[ int( $#_/2 ), ceil( $#_/2 ) ] )/2;
}

# Calculates the identity threshold based on the length of the sequence.
# The formula used is based on the research by Rost, 1999 (Twilight-zone).
# Parameters:
#   $_[0] - The length of the sequence
# Returns:
#   The identity threshold for the given sequence length.
sub identitybylength {
        # Accoding to the formula of Rost, 1999 (Twilight-zone)
  if($_[0] <= 11)   {return 100;}
  if($_[0] <= 450)  {return 480*$_[0]**(-0.32*(1+exp(-$_[0]/1000)));}
  return 19.5;
}

# This subroutine performs adaptive best blast matches based on the given reciprocal matches.
# It takes a hash reference of reciprocal matches as input and returns a hash reference of the filtered reciprocal matches.
# The filtering is done based on the best bitscore for each gene and a similarity threshold.
# Genes with bitscores below the threshold are removed from the reciprocal matches.
# The similarity threshold is defined by the variable $sim.
sub adaptive_best_blast_matches {
  my %reciprocal_matches = %{(shift)};

  if ($debug>1) {
    print STDERR "\nStart with ";
    print STDERR scalar(keys %reciprocal_matches);
    print STDERR " edges\n";
  }

  my %best;
  my %best_gen;
  # Gather best
  foreach (keys %reciprocal_matches) {
    my ($a,$b) = split(" ",$_);
    my ($evalue_ab,$bitscore_ab,$evalue_ba,$bitscore_ba) = split(" ",$reciprocal_matches{$_});
    if (!defined($best{$a}) || $best{$a} < $bitscore_ab) {
      $best{$a} = $bitscore_ab;
      $best_gen{$a} = $b;
    }
    if (!defined($best{$b}) || $best{$b} < $bitscore_ba) {
      $best{$b} = $bitscore_ba;
      $best_gen{$b} = $a;
    }
  }

  if ($debug>1) {
    my %gene_num;
    # Count gene number
    foreach (keys %reciprocal_matches) {
      my ($a,$b) = split(" ",$_);
      $gene_num{$a}++;
      $gene_num{$b}++;
    }
    print STDERR "Number of genes: ".scalar(keys %gene_num)."\n";

    foreach (keys %best) {
      print STDERR "Best score for $_ is $best{$_} ($best_gen{$_})\n";
    }
  }

  # Remove worse
  foreach (keys %reciprocal_matches) {
    my ($a,$b) = split(" ",$_);
    my ($evalue_ab,$bitscore_ab,$evalue_ba,$bitscore_ba) = split(" ",$reciprocal_matches{$_});
    if  ($best{$a}*$sim > $bitscore_ab) {delete $reciprocal_matches{$_}; if ($debug>1) {my $v = $bitscore_ab/$best{$a}; print STDERR "Removed $_ because $best{$a} vs $bitscore_ab ($v)\n";}}
    elsif   ($best{$b}*$sim > $bitscore_ba) {delete $reciprocal_matches{$_}; if ($debug>1) {my $v = $bitscore_ba/$best{$b}; print STDERR "Removed $_ because $best{$b} vs $bitscore_ba ($v)\n";}}
  }

  if ($debug>1) {
  print STDERR "\nEnd with ";
  print STDERR scalar(keys %reciprocal_matches);
  print STDERR " edges\n";

  my %gene_num;
  # Count gene number
  foreach (keys %reciprocal_matches) {
    my ($a,$b) = split(" ",$_);
    $gene_num{$a}++;
    $gene_num{$b}++;
  }
  print STDERR "Number of genes: ".scalar(keys %gene_num)."\n";}

  return \%reciprocal_matches;
}

# Function: synteny_matches
#
# Description: This function converts reciprocal matches to ffadj input and performs additional processing to identify close copies.
#
# Parameters:
#   - $reciprocal_matches: Reference to an array containing the reciprocal matches.
#   - $file_i: Path to the first file.
#   - $file_j: Path to the second file.
#
# Returns:
#   - $output: A string containing the converted ffadj input.
#   - \%track: Reference to a hash containing the reverse mapping of gene IDs.
#   - \%close_copies: Reference to a hash containing the close copies identified.
#
sub synteny_matches {
  my $reciprocal_matches = shift;
  my $file_i = shift;
  my $file_j = shift;

  # Get order for both species (same hash as ids are non overlapping)
  my %order;
  my %track;
  for my $file ($file_i, $file_j) {
    my %chr2id;
    # Get Coordinates for all genes
    my %coords = %{&read_details($file,1)};
    my $counter = 0;
    # Number them according to their order
    foreach my $id (sort
      {
        my @a = split("\t",$coords{$a});
        my @b = split("\t",$coords{$b});

        #chr pos
        if ($a[0] ne $b[0]) {return $a[0] cmp $b[0];}
        return $a[2] <=> $b[2];
      } (keys(%coords))) {
      my @v = split("\t",$coords{$id});
      if(!exists $chr2id{$v[0]}){ $chr2id{$v[0]} = scalar keys %chr2id; }
      $order{$id} = ++$counter."\t".$v[1]."\t".$chr2id{$v[0]};  # Store strand info and CHR
      $track{$file.$counter} = $id;   # Reverse Mapping
    }
  }

  my $output = "";

  my @multis; # array that contains all multi-edges
  # Convert reciprocal matches to ffadj input
  foreach (@{$reciprocal_matches}) {
    my @values = split(/\s/,$_);
    my ($a,$b,$evalue_ab,$bitscore_ab,$evalue_ba,$bitscore_ba) = @values;

    unless (defined($order{$a})) {$a = &convertUniprotAndNCBI($a);}
    unless (defined($order{$b})) {$b = &convertUniprotAndNCBI($b);}
    my @a = split(/\s/,$order{$a});
    my @b = split(/\s/,$order{$b});
    unless (defined($a[0])) {&Error("Failed parsing gene IDs from blast output/gff input\n");}

    unless (defined($multis[$a[0]])) {$multis[$a[0]] = $b[0];}
    else         {$multis[$a[0]] .= ','.$b[0];}

    $output .= "$b[2]\t$b[0]\t$a[2]\t$a[0]\t";      # Positions
    if ($a[1] eq $b[1])   {$output .= "1\t";} # Same strand?
    else      {$output .= "-1\t";}
    my $score = (&edgeweight($evalue_ab)+&edgeweight($evalue_ba))/2;  # Score made from e-values
    $output .= $score."\n";
  }

  # Check multis
  my %close_copies;
  if ($neighbourjoin) {
    for (my $i = 1; $i < scalar(@multis); $i++) {
      unless (defined($multis[$i])) {next;}
      my @partners = sort { $a <=> $b } split(',',$multis[$i]);
      if (scalar(@partners) <= 1) {next;}
      my $dist_limit = 2; # How far can tandem copies be away from each other? (0/1 = off, 2 = immediate, ...
      my $last = 999999999999999;
      foreach my $new (@partners) {
        if (abs($last-$new) < $dist_limit) {
          if (!defined($close_copies{$last}))   {$close_copies{$last} = $new;}
          else          {$close_copies{$last} .= ','.$new;}
          $close_copies{$new} = $last;    # The list is sortet, so we are here for the frist time
        }
        $last = $new;
      }
    }
  }

  return ($output, \%track, \%close_copies);
}

