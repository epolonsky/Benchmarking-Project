# Reads a file containing blast results and extracts relevant information.
# Parameters:
#   $f: The file path of the input file.
#   $data: Reference to a data structure to store the extracted information.
#   $cur_gene_lengths: Reference to a hash table to store the lengths of genes.
#   $seen: Reference to a hash table to keep track of seen gene pairs.
sub readFile_oneblast {
  my $f = shift;
  my $data = shift;
  my $cur_gene_lengths = shift;
  my $seen = shift;

  open(my $FILE,"<$f") || &Error("Error, could not open file $f: $!");
  while(<$FILE>){
    $_ =~ s/[\r\n]+$//;#chomp only removes last \n newline, now also \r are removed and all occurences
    my @a = split("\t",$_);

    my ($query_species,$query_id)=split("--",$a[0]);
    my ($subject_species,$subject_id)=split("--",$a[1]);

    if($a[0] eq $a[1]){ next; }
    if($identical && ! (int($a[2]) eq 100 && int($a[6]) == 1 && int($a[8]) == 1 && int($a[9]) == int($a[7]) && int($a[12]) == int($a[7]) && int($a[13]) == int($a[12])) ){ next; }
    if($range>=0 && !(abs(int($a[12]) - int($a[13])) <= $range)){ next; }

    &get_legal_matches_oneblast($_,$data,$cur_gene_lengths,$seen);
  }
  close($FILE);
}

# Function: get_legal_matches_oneblast
#
# Description: This function processes a single line of blast output and checks if the match meets certain criteria to be considered a legal match.
#
# Parameters:
# - $e: The blast output line to be processed.
# - $result: A reference to a hash that stores the results.
# - $cur_gene_lengths: A reference to a hash that stores the lengths of genes.
# - $seen: A reference to a hash that keeps track of seen matches.
#
# Returns: None

sub get_legal_matches_oneblast {
  my $e = shift;
  my $result = shift;
  my $cur_gene_lengths = shift;
  my $seen = shift;

  my ($query_id,$subject_id,$local_identity,$alignment_length,$mismatches,$openings,$query_start,$query_end,$subject_start,$subject_end,$local_evalue,$local_bitscore) = split(/\s+/,$e);

  if($query_id eq $subject_id){return}

  my $query_species;
  my $subject_species;
  ($query_species,$query_id)=split("--",$query_id);
  ($subject_species,$subject_id)=split("--",$subject_id);

  if($query_species eq $subject_species && !$selfblast){return}
  if($query_id eq $subject_id){return}

  $local_evalue = sprintf("%.2e", $cur_gene_lengths->{$query_species}->{$query_id} * 
                    $cur_gene_lengths->{$subject_species}->{"total"} ) / 
                    (2**$local_bitscore);

  if($local_evalue eq 'inf'){ $local_evalue=0; }

  if(!defined($query_id) || $query_id eq "" || !defined($subject_id) || $subject_id eq ""){return}

  if($blastmode eq "mmseqsp" || $blastmode eq "mmseqsn"){$local_identity = $local_identity*100;}
  if ($debug>1) {print STDERR "?$query_id -> $subject_id ($local_evalue,$local_bitscore)\n";}

  # Bug tracking
  unless ( defined($cur_gene_lengths->{$query_species}->{$query_id}) )  {if($query_id ne '#'){print STDERR "$RED [ERROR] Query gene ID '$query_id' is present in blast output but was not present in FASTA input! Skipping line. I will continue, but results may be incomplete $NC \n";} return;}
  unless ( defined($cur_gene_lengths->{$subject_species}->{$subject_id}) )  {if($query_id ne '#'){print STDERR "$RED [ERROR] Subject gene ID '$subject_id' is present in blast output but was not present in FASTA input! Skipping line. I will continue, but results may be incomplete $NC \n";} return;}

  
  ## Check for criteria
  # Well formatted
  if (!defined($local_bitscore)){return;}
  if ($evalue < $local_evalue) {return;} # 5.17, post filter e-value

  # Percent identity
  if (!$twilight && $local_identity < $identity)          {if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of identity threshold\n";} return;}
  if ( $twilight && $local_identity < &identitybylength($alignment_length)) {if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of identity by length threshold\n";} return;}
  # Min. length
  if ($blastmode eq "tblastx+" || $blastmode eq "tblastx") {$alignment_length *= 3;}

  if ($alignment_length < $cur_gene_lengths->{$query_species}->{$query_id}*($coverage/100)+0.5)     {if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of coverage threshold (alignment_length=$alignment_length<".( $cur_gene_lengths->{$query_species}->{$query_id}*($coverage/100)+0.5)."=".$cur_gene_lengths->{$query_species}->{$query_id}."*($coverage/100)+0.5)=length{query_id}*(coverage/100)+0.5,$query_id)\n";} return;}
  if ($alignment_length < $cur_gene_lengths->{$subject_species}->{$subject_id}*($coverage/100)+0.5)   {if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of coverage threshold (alignment_length=$alignment_length<".( $cur_gene_lengths->{$subject_species}->{$subject_id}*($coverage/100)+0.5)."=".$cur_gene_lengths->{$subject_species}->{$subject_id}."*($coverage/100)+0.5)=length{subject_id}*(coverage/100)+0.5,$subject_id)\n";} return;}

  {
    # Similar hits? Take the better one -> later in code
  
    # Store data
    if ($debug>1) {print STDERR "!$query_id -> $subject_id ($local_evalue,$local_bitscore)\n";}

    if(defined $seen){
      if(exists $result->{$query_species}->{$subject_species}){
        if(exists $seen->{"$query_species $query_id $subject_id"}){
          my ($remote_ga, $remote_gb, $remote_evalue, $remote_bitscore) = split(" ",$result->{$query_species}->{$subject_species}->[$seen->{"$query_species $query_id $subject_id"}]);
          if( $remote_evalue<$evalue ){ next }
        }
        $seen->{"$query_species $query_id $subject_id"}=scalar @{$result->{$query_species}->{$subject_species}}; 
      }else{
        $seen->{"$query_species $query_id $subject_id"}=0; 
      }
    }
    if(!exists $result->{$query_species}->{$subject_species}){ $result->{$query_species}->{$subject_species}=();}

    push(@{$result->{$query_species}->{$subject_species}},"$query_id $subject_id $local_evalue $local_bitscore");
  }
}

# This subroutine takes a hash reference of reciprocal matches as input and performs adaptive filtering on the matches.
# It gathers the best matches based on bitscore values and removes the matches that do not meet the filtering criteria.
# The filtering criteria is defined by the variable $sim.
# The filtered matches are updated in the original hash reference.

sub adaptive_best_blast_matches_oneblast {
  my $reciprocal_matches = shift;

  my %best;

  # Gather best
  foreach my $fa (keys %{$reciprocal_matches}) {
    foreach my $fb (keys %{$reciprocal_matches->{$fa}}) {
      if($fa ge $fb){next;}
      for (my $ii = 0; $ii < scalar @{$reciprocal_matches->{$fa}->{$fb}}; $ii++) {
        my ($ga,$gb,$evalue_ab,$bitscore_ab,$evalue_ba,$bitscore_ba) = split(" ",$reciprocal_matches->{$fa}->{$fb}->[$ii]);
        if(!exists $best{"$fa-$fb"}){$best{"$fa-$fb"}={};}

        if (!defined($best{"$fa-$fb"}{$ga}) || $best{"$fa-$fb"}{$ga} < $bitscore_ab) {
          $best{"$fa-$fb"}{$ga} = $bitscore_ab;
        }
        if (!defined($best{"$fa-$fb"}{$gb}) || $best{"$fa-$fb"}{$gb} < $bitscore_ba) {
          $best{"$fa-$fb"}{$gb} = $bitscore_ba;
        }
      }
    }
  }
  if(( scalar keys %best )== 0){return;}

  # Remove worse
  foreach my $fa (keys %{$reciprocal_matches}) {
    foreach my $fb (keys %{$reciprocal_matches->{$fa}}) {
      if($fa ge $fb){next;}
      @{$reciprocal_matches->{$fa}->{$fb}} = grep {
            my ($ga,$gb,$evalue_ab,$bitscore_ab,$evalue_ba,$bitscore_ba) = split(" ",$_);
            defined $best{"$fa-$fb"}{$gb} && defined $best{"$fa-$fb"}{$ga} && $best{"$fa-$fb"}{$ga}*$sim <= $bitscore_ab && $best{"$fa-$fb"}{$gb}*$sim <= $bitscore_ba
          } @{$reciprocal_matches->{$fa}->{$fb}};
    }
  }
}

# This subroutine represents a worker thread that performs the proteinortho analysis.
# It fetches jobs from the job queue, processes them, and generates the result.
# The result includes the reciprocal best matches between genes, synteny information, and other relevant data.
# The worker thread also handles various parameters and options related to the analysis.
# Note: Some parts of the code are still under development or disabled.

sub workerthread {

  my $thread_id = threads->tid();

  my $WD="${tmp_path}thread${thread_id}_WD";

  my %lengths;
  my $last_i="";
  my $last_j="";

  my $is_pipe_job=$pipeblast; # disabled for now, currently in development

  my $debug_time="";
  # clean the thread specific tmp file as it is filled by the thread again
  if(-e "${tmp_path}simgraph-$project-$run_id-${thread_id}"){
    unlink "${tmp_path}simgraph-$project-$run_id-${thread_id}";
  }

  while (1) {
    my ($i, $j);
    while (1) {
      # Fetch new jobs
      my $job = $jobque->dequeue_nb();

      # If there is nothing
      unless (defined($job)) {
        # Check if more jobs need to be done
        {
        lock($jobs_done);             #   Productive
        if ($jobs_done >= $jobs_todo || ($part != -1 && $jobs_done >= $part) ) { #   Productive
          if ($debug) {
            open(my $FHd,">$thread_id.err");
            print $FHd $debug_time;
            close($FHd);
          }
          threads->exit;
        }}
        # If so, wait
        if ($debug) { print STDERR "Thread $thread_id\tis seeking work ($jobs_done / $jobs_todo)\n"; }
        if ($debug) { $debug_time.=time()." idle\n"; }
        sleep(1);
      }
      else {
        # Parse job
        ($i, $j) = split(" ",$job);
        if ($debug) { $debug_time.=time()." work $i $j\n"; }
        # Break the fetch loop
        last;
      }
    }

    my $file_i = $files[$i];
    my $file_j = $files[$j];

    # update 6.3.1: try to blast in such a way that the database is large and the query is small
    # => only a slight decrease in computation time ~10%
    # blast(A,B) => A is database and B is query !
    if($halfblast && $file_i ne $file_j){
      %lengths = %{&get_gene_lengths($file_i,$file_j)};
      if($lengths{$file_i}{"total"} < $lengths{$file_j}{"total"}){
        my $tmp = $file_i;
        $file_i = $file_j;
        $file_j = $tmp;
      }
