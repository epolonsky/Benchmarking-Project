# Function: blast
# Description: This function performs a BLAST search using different algorithms based on the specified blastmode.
# Parameters:
#   $_[0]: database file
#   $_[1]: query file
#   $_[2]: thread ID
#   $_[3]: lengths
#   $_[4]: seen
#   $_[5]: cur_threads_per_process
#   $_[6]: is_pipe_job
# Returns: None
sub blast {

  my $command = "";
  my @data; # return table

  my $a = $_[0]; # database
  my $b = $_[1]; # query
  my $thread_id = $_[2];
  my $lengths = $_[3];
  my $seen = $_[4];
  my $cur_threads_per_process = $_[5];
  my $is_pipe_job = $_[6];
  #if( $blastmode eq "mmseqsp" || $blastmode eq "mmseqsn" || $blastmode eq "mmseqs" ){ if(!-d "$tmp_path/mmseqs".$thread_id ){mkdir("$tmp_path/mmseqs".$thread_id);}else{rmdir("$tmp_path/mmseqs".$thread_id);mkdir("$tmp_path/mmseqs".$thread_id);}}

  $a = basename($a);
  $b = basename($b);

  my $bla = "../blastfiles/$b.vs.$a.".$blastmode; # a is database and b is query

  my $WD="${tmp_path}/thread${thread_id}_WD";
  if(!-d $WD){ 
    system("mkdir -p '$WD'");
    if ($? != 0 || !-d $WD) {&TypicalBlastError($blastmode,"mkdir -p '$WD'","Could not create the working directory: $?",$!);}
  }

  my $blastOptions_diamond=''; #additional option --sensitive (if gene length is larger than 40)
  if($blastmode eq "diamond" && !$notsensitive){
    if (index($blastOptions, "--ultra-sensitive") == -1 && 
        index($blastOptions, "--very-sensitive") == -1 &&  
        index($blastOptions, "--mid-sensitive") == -1 &&  
        index($blastOptions, "--fast") == -1 &&  
        index($blastOptions, "--more-sensitive") == -1 && index($blastOptions, "--sensitive") == -1) {
      $blastOptions_diamond = "--sensitive";
    }
  }
  if($blastmode eq "diamond" && $blastversion =~ /^([^.]+)\.([^.]+)\.([^.]+)/ && ($1 > 2 || ($1==2 && $2 > 0) || ($1==2 && $2==0 && $3 >= 15))){
    $blastOptions_diamond .= ($blastOptions_diamond ne "" ? " " : "")."--ignore-warnings";
  }
  
  my $printSTDERR="";
  if($verbose != 2){ $printSTDERR='2>/dev/null'; }

  my ($fileType) = $a =~ /\.(\w*)$/;

  $a = "$_[0]";
  $b = "$_[1]";
  
  # check first if there is a file in the tmp/DB directory
  if(-e $tmp_path."/DB/".basename($a)){ $a = "../DB/".basename($a); }
  else{
    $a = abs_path "$_[0] ";
    $a=~s/ $//g; # this is a trick, to get the abs_path of the symlink (not the target) 1. add whitespace to filename 2. call abs_path 3. remove whitespace

    # for symlinks:
    # check if DB exists at this position, else follow the link to the true target
    if(!(()=glob(${a}.".".$blastmode.".*"))){
      $a = abs_path "$_[0]";
    }
  }
  # same for b:
  if(-e $tmp_path."/DB/".basename($b)){ $b = "../DB/".basename($b); }
  else{
    $b = abs_path "$_[1] ";
    $b=~s/ $//g; 
    if(!(()=glob(${b}.".".$blastmode.".*"))){
      $b = abs_path "$_[1]";
    }
  }

  #
  # 1. run the blast algorithm -> produce a $bla.tmp
  # 2. do some post-processing 
  # 3. rename to $bla
  # 4. load $bla to @data 
  # 5. delete $bla unless -keep
  #
  # note: e.g. diamond can directly pass the output to @data, NOTE: this make proteinortho slower, although more IO is needed to write and then read the files! (5367s to )
  # 
  # sh -ic '{ cat 1>&3; kill 0; } | { sleep 2; kill 0; }' 3>&1

  my $output_tmp_file_dir="$bla.tmp";

  if    ($blastmode eq "blastp_legacy" || $blastmode eq "blastn_legacy" || $blastmode eq "tblastx_legacy") { $command = $binpath."blastall -a $cur_threads_per_process -d '$a.$blastmode' -i '$b' -p $blastmode -m8 -e $evalue $blastOptions $printSTDERR ".(($keep || !$is_pipe_job) ? " >'$output_tmp_file_dir'" : "");}# .($keep ? " | tee '$output_tmp_file_dir'" : "");}
