# This subroutine filters the blast hit based on various criteria.
# It takes the following parameters:
# - $data: A reference to an array containing the blast hit data
# - $seen: A reference to a hash storing previously seen blast hits
# - $file_i: The identifier of the first file
# - $file_j: The identifier of the second file
# - $lengths: A reference to a hash storing the lengths of sequences
# - $line: The current line of blast hit data
sub filter_blast_hit {
  my $data=shift;
  my $seen=shift;
  my $file_i=shift;
  my $file_j=shift;
  my $lengths=shift;
  my $line=shift;

  my ($query_id,$subject_id,$local_identity,$alignment_length,$mismatches,$openings,$query_start,$query_end,$subject_start,$subject_end,$local_evalue,$local_bitscore,$len_a,$len_b) = split(/\s+/,$line);
  
  # print STDERR "->$query_id($file_i),$subject_id($file_j),$local_evalue \n";
  #  print STDERR "->$query_id($file_i),$subject_id($file_j),$local_evalue\n";

  if($identical && (
    ($local_identity ne 100) || 
    ($query_start ne 1) || 
    ($subject_start ne 1) || 
    ($subject_end ne $query_end) || 
    (defined($len_a) && defined($len_b) && $len_a != $len_b)|| 
    (defined($len_a) && $len_a != $query_end)
    )){
    return;
  }
  if( $range>=0 && defined($len_a) && defined($len_b) && abs(int($len_b - $len_a)) >$range ){
    return;
  }
  if($selfblast && $query_id eq $subject_id){
    return;
  }
  if(!defined($query_id) || $query_id eq "" || !defined($subject_id) || $subject_id eq ""){
    return;
  }

  if($blastmode eq "mmseqsp" || $blastmode eq "mmseqsn"){$local_identity = $local_identity*100;}
  # Bug tracking
  my $query_len=0;
  my $subject_len=0;
  if ( !defined($lengths->{$file_i}->{$query_id}) )  {if($query_id ne '#'){
    print STDERR "$RED [ERROR]  Query gene ID '$query_id' is present in blast output but was not present in FASTA input! Skipping line. I will continue, but results may be incomplete $NC \n";} 
    return;
  }
  if ( !defined($lengths->{$file_j}->{$subject_id}) )  {if($query_id ne '#'){
    print STDERR "$RED [ERROR]  Subject gene ID '$subject_id' is present in blast output but was not present in FASTA input! Skipping line. I will continue, but results may be incomplete $NC \n";} 
    return;
  }
  ## Check for criteria
  # Well formatted
  if (!defined($local_bitscore)){return;}
  if ($evalue < $local_evalue) {return;} # 5.17, post filter e-value
  # Percent identity
  if (!$twilight && $local_identity < $identity)          {
    if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of identity threshold\n";} 
    return;
  }
  if ( $twilight && $local_identity < &identitybylength($alignment_length)) {
    if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of identity by length threshold\n";} 
    return;
  }
  # Min. length
  if ($blastmode eq "tblastx+" || $blastmode eq "tblastx") {$alignment_length *= 3;}
  if ($alignment_length < $lengths->{$file_i}->{$query_id}*($coverage/100)+0.5)     {
    if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of coverage threshold (alignment_length=$alignment_length<".( $lengths->{$file_i}->{$query_id}*($coverage/100)+0.5)."=$lengths->{$file_i}->{$query_id}*($coverage/100)+0.5)=lengths{query_id}*(coverage/100)+0.5,$query_id)\n";} 
    return;
  }elsif ($alignment_length < $lengths->{$file_j}->{$subject_id}*($coverage/100)+0.5)   {
    if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of coverage threshold (alignment_length=$alignment_length<".( $lengths->{$file_j}->{$subject_id}*($coverage/100)+0.5)."=$lengths->{$file_j}->{$subject_id}*($coverage/100)+0.5)=lengths{subject_id}*(coverage/100)+0.5,$subject_id)\n";} 
    return;
  }else{
    if($isoform ne ""){
      my $query_id_iso=$query_id;
      my $subject_id_iso=$subject_id;
      if(exists $isoform_mapping{$file_i." ".$query_id} ){   $query_id_iso   = $isoform_mapping{$file_i." ".$query_id} }
      if(exists $isoform_mapping{$file_j." ".$subject_id} ){ $subject_id_iso = $isoform_mapping{$file_j." ".$subject_id} }
      # Similar hits? Take the better one
      # Store data
      if ($debug>1) {print STDERR "!$query_id -> $subject_id ($local_evalue,$local_bitscore)\n";}

      if(exists $seen->{"$file_i $query_id_iso $subject_id_iso"}){
        my ($remote_ga, $remote_gb, $remote_evalue, $remote_bitscore) = split(" ",$data->[$seen->{"$file_i $query_id_iso $subject_id_iso"}]);
        if( $remote_evalue<$evalue ){ return }
      }
      $seen->{"$file_i $query_id $subject_id"}=scalar @{$data};

      push( @{$data}, "$query_id_iso $subject_id_iso $local_evalue $local_bitscore" );
    }else{
      # Similar hits? Take the better one -> later
      # Store data
      if ($debug>1) {print STDERR "!$query_id -> $subject_id ($local_evalue,$local_bitscore)\n";}
      
      if(exists $seen->{"$file_i $query_id $subject_id"}){
        #print STDERR "seen: $file_i $query_id $subject_id ".(scalar @{$data})."\n";
        my ($remote_ga, $remote_gb, $remote_evalue, $remote_bitscore) = split(" ",$data->[$seen->{"$file_i $query_id $subject_id"}]);
        if ($debug>1) {print STDERR "!$query_id -> $subject_id it is not optimal\n";} 
        if( $remote_evalue<$evalue ){ return }
      }
      $seen->{"$file_i $query_id $subject_id"}=scalar @{$data};

      #print STDERR "insert $file_i $query_id $subject_id\n";

      push( @{$data}, "$query_id $subject_id $local_evalue $local_bitscore" );
    }
  }
}

# Reads a file and processes its contents.
# Parameters:
#   $fn: The file name to be read.
#   $lengths: Reference to a hash containing lengths.
#   $file_i: The value of file_i.
#   $file_j: The value of file_j.
#   $seen: Reference to a hash containing seen values.
# Returns:
#   An array containing the processed data.
sub readFile {
  my $fn = shift;
  my $lengths = shift;
  my $file_i=shift;
  my $file_j=shift;
  my $seen=shift;

  open(FILE,"<$fn") || &Error("Error, could not open file $_[0]: $!");
  my @data;
  while(<FILE>){
    $_ =~ s/[\r\n]+$//;#chomp only removes last \n newline, now also \r are removed and all occurences
    filter_blast_hit(\@data,$seen,$file_i,$file_j,$lengths,$_);
  }
  
  close(FILE);
  return @data;
}

