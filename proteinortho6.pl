# Sets the number of threads per process based on the number of jobs to be done.
# This function takes an argument representing the number of running threads and calculates the optimal number of threads per process.
# It locks the variables $jobs_done and $threads_per_process to ensure thread safety.
# If the debug flag is set, it prints the number of jobs to be done, the number of jobs already done, and the number of running threads.
# If the calculated optimal number of threads is greater than the current number of threads per process, it updates the value and prints a debug message.
# Finally, it returns the number of threads per process.

sub set_threads_per_process {
  lock($jobs_done);
  lock($threads_per_process);

  my $willdo = ($jobs_todo-$jobs_done+$_[0]);

  if ($debug) {
    print STDERR "\nTODO: $jobs_todo DONE: $jobs_done Running: $_[0] -> $willdo\n";
  }

  if ($willdo < 1) {return $threads_per_process;}

  my $optimal = int($cpus/$willdo);
  if ($optimal > $threads_per_process) {
    return $optimal;
    if ($debug) {
      print STDERR "\nBlast subthreads was set to $optimal\n";
    }
  }
  return $threads_per_process
}

# Function: run_blast
#
# Description: This function is responsible for running the blast algorithm on input files.
# It divides the jobs into multiple parts based on the number of threads and job number.
# It checks if the database file exists for each input file and throws an error if it is missing.
# It creates worker threads to perform the blast calculations in parallel.
# It waits for all the jobs to finish and prints the blast statistics.
# If multiple blast runs are performed, it merges the output files into a single file.
#
# Parameters:
#   None
#
# Returns:
#   None
sub run_blast {
  # Jobs todo
  $jobs_todo = 0;
  for (my $i = 0; $i < scalar(@files)-1+$selfblast; $i++) {$jobs_todo += scalar(@files)-$i-1+$selfblast;}

  # Divide 5.16
  $part = int($jobs_todo/$split_to_X_jobs); # Round up to not miss anything
  # print STDERR "$jobs_todo/$split_to_X_jobs = $part\n";
  my $from = ($jobnumber-1)*($part)+1;
  if ($jobnumber == 1) {$from = 1;}
  my $to = ($jobnumber-1)*($part)+$part;
  if ($jobnumber == $split_to_X_jobs) {$to = $jobs_todo;}

  $part = 1+$to-$from;  # real part

  if ($split_to_X_jobs != -1 && $part < 1) {&Error("I have problems coordinating $split_to_X_jobs groups for $jobs_todo jobs.");}
  if ($split_to_X_jobs <= 1) {$from = -1; $to = -1; $split_to_X_jobs = -1; $part = -1;}

  &print_blast_stats();

  # Spawn worker threads
  if(!$oneblast){

    for (my $i = 1; $i <= $cpus; $i++) {
      my $WD="${tmp_path}thread${i}_WD";
      if(!-d $WD){ system("mkdir -p '$WD'"); }
    }
    for (my $i = 0; $i < $cpus; $i++) {
      threads->create('workerthread');
    }
  }

  # 6.1.8: check if database file exists, if not throw an error !
  if($blastmode !~ /.*blat.*/ && $blastmode ne "dali"){
    for (my $i = 0; $i < scalar(@files)-1+$selfblast; $i++) {
      # the first abs_path_file is the location of the symlink (not the target)
      my $abs_path_file=abs_path "$files[$i] "; $abs_path_file=~s/ $//g; if(!-e $abs_path_file){$abs_path_file = abs_path "$files[$i]";if(!-e $abs_path_file){$abs_path_file = "$files[$i]";}}
      # the second one contains the true target location
      my $abs_path_file_true=abs_path $files[$i]; 

      if($debug>3){
        my $dirname=$files[$i];
        $dirname=~s/[^\/]*$//g;
        print STDERR "[DEBUG] $files[$i]:\n".
          "ls '$dirname'=".(`ls '$dirname' | tr '\\n' ','`)."\n".
          "pwd '$dirname'=".(`pwd '$dirname'`).
          "realpath '$dirname'=".(`realpath '$dirname'`).
          "glob(file.blastmode.*)=".(join ",",glob($files[$i].".".$blastmode.".*"))."\n".
          "glob(tmp_path/DB/basename(file.blastmode.*)=".(join ",",glob($tmp_path."/DB/".basename($files[$i]).".".$blastmode.".*"))."\n".
          "glob(abs_path.blastmode.*)=".(join ",",glob($abs_path_file.".".$blastmode.".*"))."\n".
          "glob(abs_path_true.blastmode.*)=".(join ",",glob($abs_path_file_true.".".$blastmode.".*"))."\n".
          "\n";
      }

      if( !$bin &&
          ! (()=glob($files[$i].".".$blastmode."*")) && 
          ! (()=glob($tmp_path."/DB/".basename($files[$i]).".".$blastmode."*")) &&
          ! (()=glob($abs_path_file.".".$blastmode."*")) &&
          ! (()=glob($abs_path_file_true.".".$blastmode."*"))
          ){
        &Error("Input file $files[$i] is missing the database file, please run -step=1 first and make sure that the database files are not deleted.");
      }
      if( $bin &&
          ! (()=glob($files[$i].".bin*.".$blastmode."*")) && 
          ! (()=glob($tmp_path."/DB/".basename($files[$i]).".bin*.".$blastmode."*")) &&
          ! (()=glob($abs_path_file.".bin*.".$blastmode."*")) &&
          ! (()=glob($abs_path_file_true.".bin*.".$blastmode."*"))
          ){
        &Error("Input file $files[$i].bin* is missing the database file, please run -step=1 first and make sure that the database files are not deleted.");
      }
    }
  }

  # For each file against each other file
  my $job_number = 0;
  SPEC: for (my $i = 0; $i < scalar(@files)-1+$selfblast; $i++) {
    for (my $j = $i+1-$selfblast; $j < scalar(@files); $j++) {
      $job_number++;
      if ($from != -1 && $job_number < $from) {next;}
      # Wait for queque to get empty (with some buffer)
      while ($jobque->pending() > 32 + 2*$cpus && !$oneblast) {sleep(1);}
      # Syncronize with other processes
      $jobque->enqueue("$i $j");
      if ($to != -1 && $job_number >= $to) {last SPEC;}
    }
  }
  # Tell all threads they can stop
  {lock($all_jobs_submitted); $all_jobs_submitted = 1;}

  # Wait until all jobs are done
  if(!$oneblast){
    foreach (threads->list())   {$_->join();}
  }else{
    &workerthread_oneblast();
  }
  &print_blast_stats();   if($verbose){print STDERR "\n";}

  if(!$oneblast){
    open(my $GRAPHout,">>$simgraph") || &Error("Could not open file '$simgraph': $!");
    foreach my $simgraph_temp_file (glob("'${tmp_path}simgraph-$project-$run_id-*'")){
      open(my $GRAPHin,"<$simgraph_temp_file") || &Error("Could not open file '$simgraph_temp_file': $!");
      while(<$GRAPHin>){
        print $GRAPHout $_;
      }
      close($GRAPHin);
    }
    close($GRAPHout);
  }

  if($verbose){print STDERR "[OUTPUT] -> written to $simgraph\n";}
}

# workerthread_oneblast subroutine performs the blast analysis for a pair of input files in a multi-threaded manner.
# It fetches jobs from a job queue, parses the job, performs the blast analysis, and aggregates the results.
# The results are then written to a simgraph file.
# The subroutine takes into account the bin parameter to determine whether to perform bin-based blast analysis or not.
# If bin is greater than 0, it searches for corresponding bin-files of file_i and file_j and performs blast analysis on them.
# The results are then aggregated and written to a temporary simgraph file.
# Finally, the contents of all temporary simgraph files are merged into the final simgraph file.
# If bin is 0, it performs blast analysis on the original input files and reduces the results to reciprocal hits.
# The reciprocal hits are then aggregated and written to the simgraph file.
# The subroutine uses locks to ensure thread safety when updating the jobs_done counter.
# It also uses a sleep function to wait for new jobs when the job queue is empty.
# The subroutine returns when all jobs are done or when a specific part of the job is completed, depending on the value of the part parameter.
# The subroutine is called within a multi-threaded context.
sub workerthread_oneblast {

  my $thread_id = threads->tid();

  while (1) {
    my ($i, $j);
    while (1) {
      # Fetch new jobs
      my $job = $jobque->dequeue_nb();
      # If there is nothing
      unless (defined($job)) {
        # Check if more jobs need to be done
        {
        lock($jobs_done);             #   Productive
        if ($jobs_done >= $jobs_todo || ($part != -1 && $jobs_done >= $part)) { #   Productive
          if ($debug) {print STDERR "Thread $thread_id\tis leaving\n";}
          if($oneblast){return;}
          threads->exit;
        }}
        # If so, wait
        if ($debug) {print STDERR "Thread $thread_id\tis seeking work ($jobs_done / $jobs_todo)\n";}
        sleep(1);
      }
      else {
        # Parse job
        ($i, $j) = split(" ",$job);
        # Break the fetch loop
        last;
      }
    }

    my $file_i = $files[$i];
    my $file_j = $files[$j];
    my $short_file_i = $file_i; $short_file_i =~ s/^.*\///;
    my $short_file_j = $file_j; $short_file_j =~ s/^.*\///;

    # Work

    my $file_nam="";

    if($bin>0){

      my @bin_files;
      my @species=keys %different_species;
      my %seen;

      foreach my $file_i_bin (glob("$file_i.bin*")) { # search for the corresponding bin-files of file_i and file_j and blast against each other

        if($file_i_bin!~/bin[0-9]+$/){next;}
        my $cur_bin_width=-1;
        if($file_i_bin=~m/.*\.bin([0-9]+)$/){$cur_bin_width=$1;}
        if(! -e "$file_j.bin$cur_bin_width"){next;}

        $file_nam = &blast_oneblast($file_i_bin,"$file_j.bin$cur_bin_width",$thread_id);

        my %current_selection;
        my %result;

        if($verbose){print STDERR "aggregating results...\n";}

        readFile_oneblast($file_nam,\%result,\%master_lengths_oneblast);
          
        {
          foreach my $fa (keys %result) {
              foreach my $fb (keys %{$result{$fa}}) {
                if($fa ge $fb){next;}
                my %seen;
                for (my $ii = 0; $ii < scalar @{$result{$fa}{$fb}}; $ii++) {
                  my ($ga, $gb, $evalue, $bitscore) = split(" ",$result{$fa}{$fb}[$ii]);
                  if(exists $seen{"$fa $ga $gb"}){
                    my ($remote_ga, $remote_gb, $remote_evalue, $remote_bitscore) = split(" ",$result{$fa}{$fb}[$seen{"$fa $ga $gb"}]);
                    if( $remote_evalue<$evalue ){ next }
                  }
                  $seen{"$fa $ga $gb"}=$ii;
                }
                if(!exists $result{$fb}{$fa}){next}
                for (my $ii = 0; $ii < scalar @{$result{$fb}{$fa}}; $ii++) {
                  my ($gb, $ga, $evalue, $bitscore) = split(" ",$result{$fb}{$fa}[$ii]);
                  if(exists $seen{"$fb $gb $ga"}){
                    my ($remote_gg, $remote_ga, $remote_evalue, $remote_bitscore) = split(" ",$result{$fb}{$fa}[$seen{"$fb $gb $ga"}]);
                    if( $remote_evalue<$evalue ){ next }
                  }
                  $seen{"$fb $gb $ga"}=$ii;
                }
                @{$result{$fa}{$fb}} = map { 
                                          my ($ga, $gb, $evalue_ab, $bitscore_ab) = split(" ",$_); 
                                          if(exists $seen{"$fb $gb $ga"}){ 
                                            my ($remote_ga, $remote_gb, $remote_evalue, $remote_bitscore) = split(" ",$result{$fb}{$fa}[$seen{"$fb $gb $ga"}]); 
                                            ( "$_ $remote_evalue $remote_bitscore" )
                                          }else{ () } }
                                        @{$result{$fa}{$fb}};
              }
          }
        }

        &adaptive_best_blast_matches_oneblast(\%result);

        my $simgraph_temp_file = "${tmp_path}simgraph-$project-$run_id-${thread_id}_${short_file_i}.$cur_bin_width";
        push(@bin_files,$simgraph_temp_file);

        open(my $GRAPH,">$simgraph_temp_file") || &Error("Could not open file '$simgraph': $!");
        my $iti = 0;

        foreach my $fa (keys %result) {
          foreach my $fb (keys %{$result{$fa}}) {
