# Calculates the edge weight based on the input value.
# The edge weight is determined using a logarithmic function.
# Parameters:
#   $_[0] - The input value for calculating the edge weight.
# Returns:
#   The calculated edge weight.
sub edgeweight {
  # 1e-10 = 0.15, 1e-20 = 0.3, 1e-40 = 0.6, 1e-66+ = 1.0
  if ($_[0] == 0) {return 1;}
  my $x = -1*&log10($_[0])/100*1.5;
  if ($x > 1) {return 1;}
  if ($x <= 0) {return 0.0001;}
  return $x;
}

# Writes sequence descriptions to a file specified by $desctable.
# If $verbose is true, it prints progress messages to STDERR.
# The descriptions are extracted from the input files specified by @files.
# Each description consists of the sequence ID and an optional annotation.
# If no annotation is found, "unannotated sequence" is used as the default.
sub write_descriptions {
  if($verbose){print STDERR "Writing sequence descriptions\n";}
  open DESC, '>', $desctable;
  foreach my $file (@files) {
    if ($verbose) {print STDERR "Extracting descriptions from '$file'\t(".$gene_counter{$file}." entries)\n";}
    open FASTA, '<', $file;
    while (<FASTA>) {
      $_=~s/[\r\n]+$//;
      if (m/^>(\S+)(\s+(.*))?$/) {
        print DESC $1, "\t", ($3 || "unannotated sequence"), "\n";
      }
    }
  }
  if($verbose){print STDERR "[OUTPUT] -> written to $desctable\n";}

}

