# This subroutine is responsible for binning input files.
# It checks if there are at least two files to compare and throws an error if not.
# It also handles the binning process by dividing the sequences into bins based on the specified bin width.
# Each bin is written to a separate output file with the format "<input_file>.bin<bin_length>".
# The subroutine also keeps track of the number of genes in each bin using the %gene_counter hash.
# Existing bin files are skipped to avoid duplication.
# The subroutine returns the updated list of files after binning.
sub bin_files {
  if ( ( scalar(@files) == 0 || (scalar(@files) == 1 && $selfblast==0) ) && $step != 3)   {&print_usage_more; &Error("I need at least two files to compare something!");}
  if($verbose){print STDERR "Binning input files";}
  if($synteny){print STDERR "the combination of -syteny and -bin is not supported (feel free to open a git issue to draw awareness to this)...\n"; exit 1;}

  my $bin_width = $bin;

  foreach my $file (@files) {
    my $is_done_allready=0;
    foreach my $fp (glob("'$file.bin*'")) { $is_done_allready=1; last; } # safe-guard

    if($is_done_allready){next;}

    open(my $MFH,"<$file") or die "ERROR $? $!\n";
    my %handles;
    my $name="";
    my $seq="";
    while(<$MFH>){
      if(substr($_,0,1)eq">"){
        if($name ne ""){
          my $len = length($seq);
          my $len_reminder = length($seq) % $bin_width;
          $len -= $len_reminder;
          my $outfilename="$file.bin$len";
          if(!exists $gene_counter{$outfilename}){$gene_counter{$outfilename}=0;}
          $gene_counter{$outfilename}++;
          if(!exists $handles{"$outfilename"}){open($handles{"$outfilename"},">$outfilename") or die "$? $!\n";}
          print {$handles{"$outfilename"}} "$name$seq";
          if($len > 0 && $len_reminder < $bin_width/10){
            $len -= $bin_width;
            $outfilename="$file.bin$len";
            if(!exists $gene_counter{$outfilename}){$gene_counter{$outfilename}=0;}
            $gene_counter{$outfilename}++;
            if(!exists $handles{"$outfilename"}){open($handles{"$outfilename"},">$outfilename") or die "$? $!\n";}
            print {$handles{"$outfilename"}} "$name$seq";
            $len += $bin_width;
          }
          if($len_reminder > $bin_width*9/10){
            $len += $bin_width;
            $outfilename="$file.bin$len";
            if(!exists $gene_counter{$outfilename}){$gene_counter{$outfilename}=0;}
            $gene_counter{$outfilename}++;
            if(!exists $handles{"$outfilename"}){open($handles{"$outfilename"},">$outfilename") or die "$? $!\n";}
            print {$handles{"$outfilename"}} "$name$seq";
          }
        }
        $name=$_;
        $seq="";
      }else{ $seq.=$_; }
    }
    close($MFH);
    foreach my $filename (keys %handles){ close $handles{$filename}; }
  }
}
