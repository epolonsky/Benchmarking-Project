# match subroutine
#
# This subroutine takes in a hash reference of sequence lengths, two file paths,
# and two arrays of matches. It calculates the legal matches for each array based
# on the sequence lengths, and then returns the reciprocal matches between the two arrays.
#
# Arguments:
#   - \%length: hash reference of sequence lengths
#   - $file_i: first file path
#   - $file_j: second file path
#   - \@i: array of matches for file_i
#   - \@j: array of matches for file_j
#
# Returns:
#   - Hash of reciprocal matches
sub match {
  my %length = %{(shift)};
  my $file_i = shift;
  my $file_j = shift;
  my @i = @{(shift)};
  my @j = @{(shift)};

  my %legal_i = &get_legal_matches(\%length,$file_i,$file_j,@i);
  my %legal_j = &get_legal_matches(\%length,$file_j,$file_i,@j);

  return &get_reciprocal_matches(\%legal_i,\%legal_j);
}

# Function: get_reciprocal_matches
#
# Description: This function takes two hash references as input and returns a hash reference containing the reciprocal matches.
#
# Parameters:
#   - %i: Hash reference representing the first set of matches
#   - %j: Hash reference representing the second set of matches
#
# Returns:
#   - \%reciprocal: Hash reference containing the reciprocal matches, where the keys are the original keys from %i and the values are the merged values from %i and %j.
#
sub get_reciprocal_matches {
  my %i = %{(shift)};
  my %j = %{(shift)};
  my %reciprocal;

  foreach (keys %i) {
    my ($i, $j) = split(" ",$_);

    # Reciprocal hit?
    if (!defined($j{"$j $i"})) {next;}

    # Merge both
    $reciprocal{$_} = $i{$_}." ".$j{"$j $i"}; # evalue_ij, bitscore_ij, evalue_ji, bitscore_ji
  }

  return \%reciprocal;
}

# Function: get_legal_matches
#
# Description: This function processes a list of matches and filters them based on various criteria such as identity, length, and coverage thresholds.
#
# Parameters:
# - $lengths: A reference to a hash containing the lengths of query and subject genes.
# - $file_i: The identifier of the first file.
# - $file_j: The identifier of the second file.
# - @_: The list of matches to be processed.
#
# Returns: A hash containing the filtered matches.
sub get_legal_matches {
  my $lengths = shift;
  my $file_i = shift;
  my $file_j = shift;

  my %result;
  foreach (@_) {
    my ($query_id,$subject_id,$local_identity,$alignment_length,$mismatches,$openings,$query_start,$query_end,$subject_start,$subject_end,$local_evalue,$local_bitscore) = split(/\s+/);

    if(!defined($query_id) || $query_id eq "" || !defined($subject_id) || $subject_id eq ""){next}

    if($blastmode eq "mmseqsp" || $blastmode eq "mmseqsn"){$local_identity = $local_identity*100;}
    if ($debug>1) {print STDERR "?$query_id -> $subject_id ($local_evalue,$local_bitscore)\n";}

    # Bug tracking
    unless ( defined($lengths->{$file_i}->{$query_id}) )  {if($query_id ne '#'){print STDERR "$RED [ERROR] Query gene ID '$query_id' is present in blast output but was not present in FASTA input! Skipping line. I will continue, but results may be incomplete $NC \n";} next;}
    unless ( defined($lengths->{$file_j}->{$subject_id}) )  {if($query_id ne '#'){print STDERR "$RED [ERROR] Subject gene ID '$subject_id' is present in blast output but was not present in FASTA input! Skipping line. I will continue, but results may be incomplete $NC \n";} next;}

    ## Check for criteria
    # Well formatted
    if (!defined($local_bitscore)){next;}
    if ($evalue < $local_evalue) {next;} # 5.17, post filter e-value

    # Percent identity
    if (!$twilight && $local_identity < $identity)          {if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of identity threshold\n";} next;}
    if ( $twilight && $local_identity < &identitybylength($alignment_length)) {if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of identity by length threshold\n";} next;}
    # Min. length
    if ($blastmode eq "tblastx+" || $blastmode eq "tblastx") {$alignment_length *= 3;}

    #if($blastmode eq "autoblast"){
    #  if($file_i eq "nucl" && $file_j eq "nucl"){
    #    $alignment_length /= 3;
    #  }
    #  # if i is nucl and j is prot -> then the alignment length is in aa length (all nucl lengths are allready /3) -> ok
    #}

    if ($alignment_length < $lengths->{$file_i}->{$query_id}*($coverage/100)+0.5)     {if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of coverage threshold (alignment_length=$alignment_length<".( $lengths->{$file_i}->{$query_id}*($coverage/100)+0.5)."=$lengths->{$file_i}->{$query_id}*($coverage/100)+0.5)=lengths->{query_id}*(coverage/100)+0.5,$query_id)\n";} next;}
    if ($alignment_length < $lengths->{$file_j}->{$subject_id}*($coverage/100)+0.5)   {if ($debug>1) {print STDERR "!$query_id -> $subject_id is removed because of coverage threshold (alignment_length=$alignment_length<".( $lengths->{$file_j}->{$subject_id}*($coverage/100)+0.5)."=$lengths->{$file_j}->{$subject_id}*($coverage/100)+0.5)=lengths->{subject_id}*(coverage/100)+0.5,$subject_id)\n";} next;}

    if($isoform ne ""){

      my $query_id_iso=$query_id;
      my $subject_id_iso=$subject_id;
      if(exists $isoform_mapping{$file_i." ".$query_id} ){   $query_id_iso   = $isoform_mapping{$file_i." ".$query_id} }
      if(exists $isoform_mapping{$file_j." ".$subject_id} ){ $subject_id_iso = $isoform_mapping{$file_j." ".$subject_id} }

      # It hit itself (only during selfblast)
      # if ($selfblast && $query_id eq $subject_id)           {next;} # 5.16 reuse IDs
      ## Listing them in the graph is okay, clustering will ignore them

      # Similar hits? Take the better one
      if (defined($result{"$query_id_iso $subject_id_iso"})) {
        my ($remote_evalue, $remote_bitscore) = split(" ",$result{"$query_id_iso $subject_id_iso"});
        if ($local_evalue > $remote_evalue) {next;}
        if ($local_bitscore < $remote_bitscore) {next;}
      }

      # Store data
      if ($debug>1) {print STDERR "!$query_id -> $subject_id ($local_evalue,$local_bitscore)\n";}
      $result{"$query_id_iso $subject_id_iso"} = "$local_evalue $local_bitscore";

    }else{

      # It hit itself (only during selfblast)
      # if ($selfblast && $query_id eq $subject_id)           {next;} # 5.16 reuse IDs
      ## Listing them in the graph is okay, clustering will ignore them

      # Similar hits? Take the better one
      if (defined($result{"$query_id $subject_id"})) {
        my ($remote_evalue, $remote_bitscore) = split(" ",$result{"$query_id $subject_id"});
        if ($local_evalue > $remote_evalue) {next;}
        if ($local_bitscore < $remote_bitscore) {next;}
      }

      # Store data
      if ($debug>1) {print STDERR "!$query_id -> $subject_id ($local_evalue,$local_bitscore)\n";}
      $result{"$query_id $subject_id"} = "$local_evalue $local_bitscore";
    }
   
  }

  return %result;
}

# Auto set the number of CPUs
sub auto_cpus {
  if ($cpus == 0) {
    my $cpu_x = qx(getconf _NPROCESSORS_ONLN);    $cpu_x =~ s/[^0-9]//g;
    # Fallback
    if (length($cpu_x) == 0 || $cpu_x == 0) {
      # Linux
      if (-e "/proc/cpuinfo") {
        $cpu_x = qx(grep processor /proc/cpuinfo | wc -l);
      }
      # Try Mac
      else {
        $cpu_x = qx(system_profiler | grep CPUs:);
      }
      $cpu_x =~ s/[^0-9]//g;
    }
    if (length($cpu_x) == 0 || $cpu_x == 0) {
      print STDERR "failed! Use 1 core only\n";$cpu_x = 1;
    }
    if($cpu_x>=16 && !$did_set_threads_per_process && $threads_per_process == 1 && sqrt($cpu_x) % 4 == 0 && $step!=3 && !$oneblast){
      $threads_per_process = 4;
      $cpu_x = int($cpu_x/4);
    }
    if($step==3 && $threads_per_process>1){ $cpu_x = $cpu_x * $threads_per_process; }

    if($verbose){print STDERR "Detected ".($cpu_x*$threads_per_process)." CPU threads ($threads_per_process threads per processes each with $cpu_x threads) adjust this with -cpus, ";}
    $cpus = int($cpu_x);
  }
  else {
    if($verbose){print STDERR "Using ".($cpus*$threads_per_process)." CPU threads ($threads_per_process threads per processes each with $cpus threads), ";}
  }
}

# This subroutine is responsible for logging worker threads.
# It runs in a separate thread and continuously checks the log_QUEUE for pending log messages.
# Once a log message is available, it dequeues it and prints it to STDERR if the verbose flag is set.
# The subroutine also checks the status of other queues and the running threads to determine when to stop logging.
# It sleeps for 1 second between iterations to avoid excessive CPU usage.
# When there are no pending log messages and all other queues are empty and no threads are running, it sets the do_log flag to 0 and exits the thread.
# This subroutine is designed to be used in a multi-threaded environment.
sub log_Worker {
  local $SIG{KILL} = sub { threads->exit };
  my $tid = threads->tid();
  if($debug){ print STDERR "log_Worker : $tid spawn\n"; }
  while($do_log){
    while($log_QUEUE->pending()){
      if($debug){ print STDERR "log_Worker inside : $tid active threads=".(scalar grep { $_->is_running() } threads->list())." log_QUEUE=".$log_QUEUE->pending()." step1_QUEUE=".$step1_QUEUE->pending()." check_files_QUEUE=".$check_files_QUEUE->pending()."\n"; }
      my $log = $log_QUEUE->dequeue();
      if($verbose){ print STDERR $log; }
    }
    if($debug){ print STDERR "log_Worker : $tid active threads=".(scalar grep { $_->is_running() } threads->list())." log_QUEUE=".$log_QUEUE->pending()." step1_QUEUE=".$step1_QUEUE->pending()." check_files_QUEUE=".$check_files_QUEUE->pending()."\n"; }
    if(!$log_QUEUE->pending() && !$step1_QUEUE->pending() && !$check_files_QUEUE->pending() && (scalar grep { $_->is_running() } threads->list()) <= 0){$do_log=0}
    sleep 1;
  }
  if($debug){ print STDERR "log_Worker : $tid dead\n"; }
  threads->exit;
}
# Subroutine: generate_indices_Worker
# Description: This subroutine is used by multiple threads to generate indices for proteinortho6.pl.
# Parameters:
#   - None
# Returns:
#   - None

sub generate_indices_Worker {
  my $tid = threads->tid();
  local $SIG{KILL} = sub { threads->exit };
  if($debug){print STDERR "generate_indices_Worker:$tid spawn\n"}
  while($step1_QUEUE->pending()){
    if($debug){print STDERR "generate_indices_Worker:$tid while\n"}
    my $file = $step1_QUEUE->dequeue();
    if(!defined($file)){last;}
    if($debug){print STDERR "generate_indices_Worker:$tid working on $file\n"}
    &generate_indices($file);
    if($debug){print STDERR "generate_indices_Worker:$tid ok with $file\n"}
  }
  if($debug){print STDERR "generate_indices_Worker:$tid dead\n"}
  threads->exit;
}
