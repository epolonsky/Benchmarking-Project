# Function: convertUniprotAndNCBI
#
# Description: This function takes a long ID string as input and converts it to either an NCBI format or a Uniprot format.
#              The function checks the number of '|' characters in the input string to determine the format.
#              If there are more than 3 '|' characters, it returns the last column of the input string, which represents the NCBI format.
#              If there are exactly 3 '|' characters, it returns the second element of the input string, which represents the Uniprot format.
#              If there are no '|' characters, it returns the input string as it is, indicating that it is neither in NCBI nor Uniprot format.
#
# Parameters:
#   - $long_id: The long ID string to be converted.
#
# Returns:
#   - The converted ID string in either NCBI or Uniprot format, or the original input string if it is neither in NCBI nor Uniprot format.
#
sub convertUniprotAndNCBI {
  my $long_id = shift;
  $long_id =~ s/\|$//g;
  my @tmp = split(/\|/,$long_id); 
  if(scalar @tmp > 3){
    return pop(@tmp); # take the last column for NCBI format like patterns (e.g. gi|158333234|ref|YP_001514406.1|)
  }elsif(scalar @tmp == 3){
    return $tmp[1]; # uniprot tr|A0A0A0MPE6|A0A0A0MPE6_DANRE -> A0A0A0MPE6
  }else{
    return $long_id; # is neither ncbi nor uniprot 
  } 
}

